"""Devices and login history (plan section 6, "My subscription" > Security).

- A user sees and signs out their own sessions, and sees their own login history.
- Organisation owners and admins see their organisation's login history.
- NOVA ARI admins (all organisations) come with the admin console (M4).
The BFF sends `X-Nova-Session-Ref` (the current session's `user_sessions.id`) so "this device" can
be marked; it is generated by the BFF only, behind the internal secret.
"""
from __future__ import annotations

import uuid
from datetime import datetime, timezone

from fastapi import APIRouter, Depends, Header, Query, Response
from sqlalchemy.orm import Session

from app.core.config import get_settings
from app.core.entitlements import require_active_membership
from app.core.http import PublicAPIError
from app.core.security import RequestContext, get_request_context, verify_internal_secret
from app.db.session import get_db
from app.models.identity import Organization, User
from app.models.sessions import UserSession
from app.schemas.sessions import DeviceList, DeviceSession, LoginHistoryEntry, LoginHistoryPage, SignOutOthersResponse
from app.services.access_management import authorize
from app.services.billing import limits
from app.services.sessions import tracking
from app.services.sessions.tracking import SessionTracker, get_session_tracker

router = APIRouter(prefix="/account", tags=["Account"], dependencies=[Depends(verify_internal_secret)])
org_router = APIRouter(prefix="/organizations/{organization_id}/administration", tags=["Administration"],
                       dependencies=[Depends(verify_internal_secret)])

ATTRIBUTION = "IP geolocation by DB-IP"


def _user(db: Session, context: RequestContext) -> None:
    if context.is_service:
        raise PublicAPIError(403, "organization_context_required", "An organisation session is required.")
    require_active_membership(db, context)


def _ref(value: str | None) -> uuid.UUID | None:
    try:
        return uuid.UUID(value) if value else None
    except ValueError:
        return None


def _location(row: UserSession) -> str | None:
    return ", ".join(part for part in (row.city, row.country) if part) or None


def _result(row: UserSession, now: datetime) -> str:
    if row.end_reason:
        return row.end_reason
    return "active" if row.expires_at > now else "expired"


def _entry(row: UserSession, now: datetime, user: User | None = None) -> LoginHistoryEntry:
    return LoginHistoryEntry(
        id=row.id, created_at=row.created_at, browser=row.browser, os=row.os, device_type=row.device_type,
        location=_location(row), country_code=row.country_code, result=_result(row, now), ended_at=row.ended_at,
        is_new_device=row.is_new_device, user_id=user.id if user else None,
        user_display_name=user.display_name if user else None, user_email=user.email if user else None)


def _redis_unavailable(exc: Exception) -> PublicAPIError:
    return PublicAPIError(503, "sessions_unavailable", "Sessions cannot be changed right now. Try again shortly.")


@router.get("/sessions", response_model=DeviceList)
def list_devices(
    db: Session = Depends(get_db), context: RequestContext = Depends(get_request_context),
    tracker: SessionTracker = Depends(get_session_tracker),
    session_ref: str | None = Header(None, alias="X-Nova-Session-Ref"),
) -> DeviceList:
    _user(db, context)
    now = datetime.now(timezone.utc)
    rows = tracking.active(db, context.user_id, now)
    try:  # hide sessions Redis no longer has (for example after a Redis restart)
        alive = tracker.alive([row.session_hash for row in rows])
        rows = [row for row in rows if row.session_hash in alive]
    except Exception:
        pass
    names = dict(db.query(Organization.id, Organization.name).filter(
        Organization.id.in_({row.organization_id for row in rows}))) if rows else {}
    current = _ref(session_ref)
    return DeviceList(
        items=[DeviceSession(
            id=row.id, created_at=row.created_at, last_seen_at=row.last_seen_at, expires_at=row.expires_at,
            browser=row.browser, os=row.os, device_type=row.device_type, location=_location(row),
            country_code=row.country_code, organization_name=names.get(row.organization_id),
            current=row.id == current) for row in rows],
        session_limit=limits.session_limit(db, context.organization_id),
        location_attribution=ATTRIBUTION if get_settings().geoip_database_path else None)


@router.post("/sessions/{session_id}/sign-out", status_code=204)
def sign_out_device(
    session_id: uuid.UUID,
    db: Session = Depends(get_db), context: RequestContext = Depends(get_request_context),
    tracker: SessionTracker = Depends(get_session_tracker),
) -> Response:
    _user(db, context)
    row = db.get(UserSession, session_id)
    if row is None or row.user_id != context.user_id:  # another user's session does not exist for you
        raise PublicAPIError(404, "session_not_found", "Session not found.")
    if row.ended_at is None:
        try:
            tracker.end(db, row, reason="ended_by_user")
        except Exception as exc:
            db.rollback()
            raise _redis_unavailable(exc) from exc
        db.commit()
    return Response(status_code=204)


@router.post("/sessions/sign-out-others", response_model=SignOutOthersResponse)
def sign_out_other_devices(
    db: Session = Depends(get_db), context: RequestContext = Depends(get_request_context),
    tracker: SessionTracker = Depends(get_session_tracker),
    session_ref: str | None = Header(None, alias="X-Nova-Session-Ref"),
) -> SignOutOthersResponse:
    _user(db, context)
    current = _ref(session_ref)
    if current is None:
        raise PublicAPIError(409, "current_session_unknown", "Sign in again, then sign out the other devices.")
    others = [row for row in tracking.active(db, context.user_id) if row.id != current]
    try:
        for row in others:
            tracker.end(db, row, reason="ended_by_user")
    except Exception as exc:
        db.rollback()
        raise _redis_unavailable(exc) from exc
    db.commit()
    return SignOutOthersResponse(ended=len(others))


@router.get("/login-history", response_model=LoginHistoryPage)
def my_login_history(
    limit: int = Query(25, ge=1, le=100), offset: int = Query(0, ge=0),
    db: Session = Depends(get_db), context: RequestContext = Depends(get_request_context),
) -> LoginHistoryPage:
    _user(db, context)
    query = db.query(UserSession).filter(UserSession.user_id == context.user_id)
    now = datetime.now(timezone.utc)
    rows = query.order_by(UserSession.created_at.desc(), UserSession.id).offset(offset).limit(limit).all()
    return LoginHistoryPage(items=[_entry(row, now) for row in rows], total=query.count(), limit=limit, offset=offset)


@org_router.get("/login-history", response_model=LoginHistoryPage)
def organization_login_history(
    organization_id: uuid.UUID,
    user_id: uuid.UUID | None = None,
    limit: int = Query(25, ge=1, le=100), offset: int = Query(0, ge=0),
    db: Session = Depends(get_db), context: RequestContext = Depends(get_request_context),
) -> LoginHistoryPage:
    """Sign-ins into this organisation (owners and admins only)."""
    authorize(db, context, organization_id)
    query = db.query(UserSession, User).join(User, User.id == UserSession.user_id).filter(
        UserSession.organization_id == context.organization_id)
    if user_id is not None:
        query = query.filter(UserSession.user_id == user_id)
    now = datetime.now(timezone.utc)
    rows = query.order_by(UserSession.created_at.desc(), UserSession.id).offset(offset).limit(limit).all()
    return LoginHistoryPage(items=[_entry(row, now, user) for row, user in rows], total=query.count(),
                            limit=limit, offset=offset)
